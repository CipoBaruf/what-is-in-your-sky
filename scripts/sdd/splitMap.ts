/**
 * Where a section goes: `index` stays in the root file; a version (`mvp`, `v1` … `v2.12`) is that
 * phase folder's spec.md, plan.md or tasks.md; `decisions` is `docs/sdd/decisions.md`;
 * `ref:<name>` is `docs/sdd/reference/<name>.md`; `stories` splits SPEC §3.2 story by story,
 * each to the phase its *(vX)* tag names (untagged: `mvp`).
 */
export type Destination = string;

interface MapSection {
  /** The `##` heading's text. */
  h: string;
  to: Destination;
  /** Its `###` headings, bare (the parent's destination) or with their own. */
  sub?: readonly (string | readonly [string, Destination])[];
}

export interface DocMap {
  /** The lines before the first `##`: the title and the header table. */
  preamble: Destination;
  sections: readonly MapSection[];
}


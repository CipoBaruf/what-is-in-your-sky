/**
 * D-1059: every `##` and `###` heading of SPEC.md, PLAN.md and TASKS.md with its destination,
 * written once from `rg -n "^#"`. A heading not in the map, or a map entry with no heading, fails
 * the split. A `###` listed bare goes where its `##` goes.
 */

/** The three documents, in the order the split reads them. */

/**
 * FR-SDD-24 (D-1069): `docs/sdd/reference/traceability.md` writes itself from the test titles.
 * The hand-kept rows of PLAN §12 stay above `GENERATED_HEADING` byte for byte; below it, one row
 * per requirement or story id a Vitest or Playwright title names, with the test files naming it.
 * CLI: `--write` regenerates the file, `--check` fails when it is stale. It reads titles, not
 * what a test asserts: a title that names an id it does not test is not caught here.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const TRACEABILITY_PATH = 'docs/sdd/reference/traceability.md';
export const GENERATED_HEADING = '## From the test names (FR-SDD-24)';

/** D-1069's id pattern, plus a story's `US-<n>`, which the decision's pattern cannot match. */
const ID = /\b(?:FR-[A-Z0-9]+-\d+[a-z]?|US-\d+)\b/g;

/** A `describe`, `it` or `test` call (`.skip`, `.each(…)`, `test.describe.serial` and the like) and its literal title. */
const TITLE = /\b(?:describe|it|test)(?:\.(?:skip|only|todo|fixme|concurrent|serial|parallel|describe|each\([^)]*\)))*\(\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/g;

/** The titles a test file's source holds, in order. */
export function testTitles(source: string): string[] {
  return [...source.matchAll(TITLE)].map((match) => match[2] ?? '');
}

/** The ids a title names. */
export const titleIds = (title: string): string[] => title.match(ID) ?? [];

/** Tracked test files: unit tests and e2e specs, the driver's own fixtures left out. */
function listTestFiles(root: string): string[] {
  return execFileSync('git', ['-C', root, 'ls-files', '-z', '--', '*.test.ts', '*.test.tsx', '*.spec.ts'], { encoding: 'utf8', maxBuffer: 1e8 })
    .split('\0')
    .filter((path) => path !== '' && !path.includes('__fixtures__/') && existsSync(join(root, path)))
    .sort();
}

/** Natural order: `FR-SDD-2` before `FR-SDD-10`. */
const byId = (a: string, b: string): number => a.localeCompare(b, 'en', { numeric: true });

/** id → the files whose titles name it, from path → source. */
export function collectTraces(files: ReadonlyMap<string, string>): Map<string, string[]> {
  const traces = new Map<string, Set<string>>();
  for (const [path, source] of files)
    for (const title of testTitles(source))
      for (const id of titleIds(title)) {
        const set = traces.get(id) ?? new Set<string>();
        set.add(path);
        traces.set(id, set);
      }
  return new Map([...traces.keys()].sort(byId).map((id) => [id, [...(traces.get(id) ?? [])].sort()]));
}

/** The text above the generated part: the whole file when it has none yet. */
export function handKept(text: string): string {
  const at = text.indexOf(`\n${GENERATED_HEADING}\n`);
  return at < 0 ? text : text.slice(0, at);
}

/** The file: the hand-kept rows, then the generated table. */
export function renderTraceability(kept: string, traces: ReadonlyMap<string, readonly string[]>): string {
  const rows = [...traces].map(([id, paths]) => `| ${id} | ${paths.map((path) => `\`${path}\``).join(', ')} |`);
  return [
    kept,
    GENERATED_HEADING,
    '',
    '<!-- Generated by `npx tsx scripts/sdd/traceability.ts --write` (D-1069): every requirement or story id a test title names. -->',
    '',
    '| Requirement | Tests |',
    '|---|---|',
    ...rows,
    '',
  ].join('\n');
}

/** The file as the tree at `root` would generate it. */
export function generateTraceability(root: string): string {
  const path = join(root, TRACEABILITY_PATH);
  const kept = handKept(existsSync(path) ? readFileSync(path, 'utf8') : '');
  const files = new Map(listTestFiles(root).map((file) => [file, readFileSync(join(root, file), 'utf8')]));
  return renderTraceability(kept, collectTraces(files));
}

/** The ids the generated table lists, read back from the file. */
export function tracedIds(text: string): Set<string> {
  const at = text.indexOf(`\n${GENERATED_HEADING}\n`);
  if (at < 0) return new Set();
  return new Set([...text.slice(at).matchAll(/^\| ([^|\s]+) \|/gm)].map((match) => match[1] ?? '').filter((id) => id !== 'Requirement'));
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = generateTraceability('.');
  if (process.argv.includes('--write')) {
    writeFileSync(TRACEABILITY_PATH, next);
    console.log(`traceability: ${TRACEABILITY_PATH} written`);
  } else {
    const stale = !existsSync(TRACEABILITY_PATH) || readFileSync(TRACEABILITY_PATH, 'utf8') !== next;
    console.log(stale ? `traceability: ${TRACEABILITY_PATH} is stale; run \`npx tsx scripts/sdd/traceability.ts --write\`` : `traceability: ${TRACEABILITY_PATH} is current`);
    process.exitCode = stale ? 1 : 0;
  }
}

/**
 * FR-SDD-14: the generated code map, `docs/sdd/map.md`, one line per source file.
 *
 *   npx tsx scripts/sdd-map.ts          # rewrite docs/sdd/map.md
 *   npx tsx scripts/sdd-map.ts --check  # exit 1 when the file on disk is stale
 *
 * An agent that wants a source file reads one line of this map (path, the first
 * sentence of the file's doc comment, its exports) before it opens anything.
 * Covers `src/` and `scripts/`, leaves out tests, `.d.ts` files and snapshots.
 * R179's `check:sdd` calls `--check`, so a stale map fails CI (D-1057).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The directories the map covers, relative to the root. */
export const MAP_DIRS = ['src', 'scripts'] as const;

/** Where the generated map lives, relative to the root. */
export const MAP_PATH = 'docs/sdd/map.md';

const SENTENCE_MAX = 140;
const EXPORTS_MAX = 8;

const HEADER = [
  '# Code map',
  '',
  'Generated by `npx tsx scripts/sdd-map.ts` (FR-SDD-14); do not edit by hand.',
  'One line per tracked source file under `src/` and `scripts/`, as ``- `path` — exports: a, b — description``.',
  'The fields are split by the first two ` — `; the exports field is always there (`exports: none` when the file has none).',
  'The description, the first sentence of the file\'s leading doc comment, is the rest of the line and may itself contain ` — `; a file with no leading doc comment has no description.',
  'Tests, `.d.ts` files and snapshots are left out.',
  '',
].join('\n');

const isSource = (path: string): boolean =>
  /\.(ts|tsx)$/.test(path) &&
  !/\.test\.(ts|tsx)$/.test(path) &&
  !/\.d\.ts$/.test(path) &&
  !path.includes('__snapshots__/') &&
  !path.includes('node_modules/');

/** Tracked files under the map's directories, sorted (the root must be a git work tree). */
export function listSourceFiles(root: string): string[] {
  return execFileSync('git', ['-C', root, 'ls-files', '-z', '--', ...MAP_DIRS], {
    encoding: 'utf8',
    maxBuffer: 1e8,
  })
    .split('\0')
    .filter(Boolean)
    .filter((f) => existsSync(join(root, f)))
    .filter(isSource)
    .sort();
}

/** Abbreviations whose dot does not end a sentence. */
const ABBREVIATIONS = /(?:^|[\s(])(?:e\.g|i\.e|vs|etc|No)$/;

/** An import statement at the start of `rest`, up to its module string and optional `;`. */
const IMPORT = /^import(?=[\s{*'"])[^'"]*(['"])[^'"\n]*\1[^\S\n]*;?/;

/** A declaration line: a one-line `/** … *\/` directly above one is its JSDoc, not a file header. */
const DECLARATION = /^(?:export|const|let|var|function|class|abstract|type|interface|enum|declare|async)\b/;

/**
 * The file's leading doc comment: the first `/** … *\/` before any code, past a
 * shebang, blank lines, `//` lines, plain block comments and import statements
 * (`import type` and multi-line ones too). A one-line doc comment whose next
 * line is a declaration, with no blank line between, belongs to that
 * declaration and is not taken; a multi-line block there is still the file's
 * header, which is how this repo writes them (the file comment sits on the
 * first declaration after the imports). Undefined when code (or nothing) comes
 * first.
 */
function leadingDocComment(source: string): string | undefined {
  let rest = source.replace(/^\uFEFF/, '').replace(/^#![^\n]*\n?/, '');
  for (;;) {
    rest = rest.replace(/^\s+/, '');
    if (rest.startsWith('//')) {
      const nl = rest.indexOf('\n');
      rest = nl === -1 ? '' : rest.slice(nl + 1);
    } else if (rest.startsWith('/**') && !rest.startsWith('/**/')) {
      const close = rest.indexOf('*/', 3);
      if (close === -1) return undefined;
      const after = /^[^\S\n]*\n([^\n]*)/.exec(rest.slice(close + 2));
      const oneLine = !rest.slice(0, close).includes('\n');
      if (oneLine && after?.[1] !== undefined && DECLARATION.test(after[1].trim())) return undefined;
      return rest.slice(3, close);
    } else if (IMPORT.test(rest)) {
      rest = rest.replace(IMPORT, '');
    } else if (rest.startsWith('/*')) {
      const close = rest.indexOf('*/', 2);
      if (close === -1) return undefined;
      rest = rest.slice(close + 2);
    } else return undefined;
  }
}

/** The first sentence of the file's leading doc comment, or '' when it has none. */
export function firstSentence(source: string): string {
  const block = leadingDocComment(source);
  if (block === undefined) return '';
  const text = block
    .split('\n')
    .map((l) => l.replace(/^\s*\*? ?/, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
  // A sentence ends at ". " (or the end), not after e.g., i.e., vs., etc. or No.;
  // a colon in `npx tsx a.ts:` stays inside.
  let sentence = text;
  for (const m of text.matchAll(/\.(?=\s|$)/g)) {
    if (ABBREVIATIONS.test(text.slice(0, m.index))) continue;
    sentence = text.slice(0, m.index + 1);
    break;
  }
  if (sentence.length > SENTENCE_MAX) sentence = `${sentence.slice(0, SENTENCE_MAX - 1).trimEnd()}…`;
  return sentence;
}

/** The names a module exports, in source order, without duplicates. */
export function exportNames(source: string): string[] {
  const names: string[] = [];
  const decl =
    /^export\s+(?:declare\s+)?(?:async\s+)?(?:const|let|var|function\*?|class|abstract\s+class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm;
  for (const m of source.matchAll(decl)) if (m[1] !== undefined) names.push(m[1]);
  for (const m of source.matchAll(/^export\s*(?:type\s*)?\{([^}]*)\}/gm)) {
    for (const part of (m[1] ?? '').split(',')) {
      const name = part
        .trim()
        .replace(/^type\s+/, '')
        .split(/\s+as\s+/)
        .pop();
      if (name) names.push(name.trim());
    }
  }
  for (const m of source.matchAll(/^export\s+\*\s*(?:as\s+([A-Za-z_$][\w$]*)\s+)?from\s*(['"][^'"]+['"])/gm)) {
    names.push(m[1] !== undefined ? `* as ${m[1]} from ${m[2]}` : `* from ${m[2]}`);
  }
  if (/^export\s+default\b/m.test(source)) names.push('default');
  return [...new Set(names)];
}

/** One map line for a file: path, exports, then the description (see HEADER). */
export function mapLine(path: string, source: string): string {
  const sentence = firstSentence(source);
  const names = exportNames(source);
  const shown = names.slice(0, EXPORTS_MAX).join(', ');
  const more = names.length > EXPORTS_MAX ? `, +${names.length - EXPORTS_MAX}` : '';
  const parts = [`- \`${path}\``, names.length > 0 ? `exports: ${shown}${more}` : 'exports: none'];
  if (sentence) parts.push(sentence);
  return parts.join(' — ');
}

/** The whole map for the tree at `root`. */
export function renderMap(root: string): string {
  const lines = listSourceFiles(root).map((f) => mapLine(f, readFileSync(join(root, f), 'utf8')));
  return `${HEADER}\n${lines.join('\n')}\n`;
}

/** Writes or checks the map; returns the process exit code. */
export function run(root: string, check: boolean, log: (m: string) => void = console.log): number {
  const target = join(root, MAP_PATH);
  const next = renderMap(root);
  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current === next) return 0;
    log(`${MAP_PATH} is stale: run \`npx tsx scripts/sdd-map.ts\` and commit it.`);
    return 1;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, next);
  log(`wrote ${relative(root, target)}`);
  return 0;
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = run(resolve(here, '..'), process.argv.includes('--check'));
}
